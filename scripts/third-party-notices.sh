#!/usr/bin/env bash
# Collects the license of every module the shipped binaries link into one
# notices file. Run before a tag; the result ships with the release.
#
# The list is what the build actually compiles in, read from `go list -deps`
# over the binaries this repository ships — not `go list -m all`, which also
# names modules the graph requires but no binary links. A dependency that ships
# must appear; one that does not ship must not be claimed.
#
# The output is a build artefact: it describes the module graph at the moment it
# runs. A module with no readable licence fails the run rather than being
# skipped, because a notices file that omits a dependency is a licence claim
# nobody can stand behind.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="${1:-$root/THIRD-PARTY-NOTICES.md}"

cd "$root"

{
  echo "# Third-party notices"
  echo
  echo "Generated by \`scripts/third-party-notices.sh\` from the modules the"
  echo "shipped binaries link. Every such module is listed; a module without a"
  echo "readable license file is called out so the release can be stopped before"
  echo "it ships."
  echo
} > "$out"

# The binaries this repository ships. flt-fake-acp-agent is a test fixture and
# is deliberately absent: it must not appear in a release's notices.
packages=(./cmd/flt ./cmd/flt-daemon ./cmd/flt-session-host ./cmd/flt-replay-agent)

status=0
while IFS='|' read -r path version dir; do
  [ -z "$path" ] && continue

  if [ -z "$dir" ]; then
    echo "no module directory for $path $version: run 'go mod download'" >&2
    status=1
    continue
  fi

  license="$(find "$dir" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \) 2>/dev/null | sort | head -1)"

  {
    echo "## $path $version"
    echo
  } >> "$out"

  if [ -z "$license" ]; then
    {
      echo "**No license file in the module cache — resolve before shipping.**"
      echo
    } >> "$out"
    continue
  fi

  {
    echo "Source: \`$(basename "$license")\`"
    echo
    echo '```'
    cat "$license"
    echo '```'
    echo
  } >> "$out"
done < <(go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}{{end}}' "${packages[@]}" |
  sort -u)

if [ "$status" -ne 0 ]; then
  exit "$status"
fi

# The renderer bundle ships node modules' code, so the gui's pnpm graph is
# noticed alongside the Go one; the emitter fails the run on unreadable
# licenses rather than shipping unknown-licensed code.
node "$root/scripts/third-party-notices-node.mjs" >> "$out"

echo "wrote $out"
