#!/usr/bin/env bash
# Collects the license of every module in the build into one notices file.
# Run before a tag; the result ships with the release.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="${1:-$root/THIRD-PARTY-NOTICES.md}"

cd "$root"

{
  echo "# Third-party notices"
  echo
  echo "Generated by \`scripts/third-party-notices.sh\` from the module graph of"
  echo "this commit. Every module the build links is listed; a module without a"
  echo "license file is called out so the release can be stopped before it ships."
  echo
} > "$out"

go list -m -f '{{if and .Dir (not .Main)}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}' all |
  while IFS='|' read -r path version dir; do
    [ -z "$path" ] && continue

    license="$(find "$dir" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \) 2>/dev/null | sort | head -1)"

    {
      echo "## $path $version"
      echo
    } >> "$out"

    if [ -z "$license" ]; then
      {
        echo "**No license file in the module cache — resolve before shipping.**"
        echo
      } >> "$out"
      continue
    fi

    {
      echo "Source: \`$(basename "$license")\`"
      echo
      echo '```'
      cat "$license"
      echo '```'
      echo
    } >> "$out"
  done

echo "wrote $out"
